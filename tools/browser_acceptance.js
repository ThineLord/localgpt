// Run this function with Playwright CLI run-code against demo.py on port 8191.
// Screenshots stay in ignored output/playwright. Never target a personal database.
async (page) => {
  if (new URL(page.url()).port !== '8191') throw new Error('Synthetic demo on port 8191 required');
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const results = {};
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const screenshot = name => page.screenshot({path:`output/playwright/after-${name}.png`,scale:'css'});
  const waitIdle = () => page.waitForFunction(() => document.querySelector('#cancel').hidden && document.querySelector('#activity').hidden);
  await page.setViewportSize({width:1440,height:900});
  await page.evaluate(() => { localStorage.setItem('qwen-studio-theme','light'); localStorage.setItem('qwen-studio-language','zh'); localStorage.setItem('qwen-studio-sidebar','open'); });
  await page.reload();
  await page.locator('#chatList .chat-item').first().waitFor();
  await page.locator('#newChat').click();
  await page.locator('#intro').waitFor({state:'visible'});
  results.desktop = await page.evaluate(() => {
    const box = id => {const r=document.getElementById(id).getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height,bottom:r.bottom};};
    const input = document.querySelector('.prompt-wrap').getBoundingClientRect();
    return {sidebar:box('sidebar'),composer:{x:input.x,y:input.y,width:input.width,height:input.height},heading:document.querySelector('h1').getBoundingClientRect().y,overflow:document.documentElement.scrollWidth>innerWidth};
  });
  check(!results.desktop.overflow,'Desktop overflow');
  check(Math.abs(results.desktop.sidebar.width-260)<2,'Sidebar must be 260px');
  check(results.desktop.composer.width<=770,'Composer must respect reference content width');
  check(Math.abs(results.desktop.heading-386)<2 && Math.abs(results.desktop.composer.y-462)<2,'Empty layout must match observed reference');
  await screenshot('desktop-empty');
  await page.locator('#mode').selectOption('chat');
  await page.locator('#prompt').fill('用清晰的结构介绍本地聊天与图像生成。This is a synthetic UI acceptance conversation.');
  await page.locator('#prompt').press('Enter');
  await page.locator('#cancel').waitFor({state:'visible'});
  await page.waitForFunction(() => document.querySelector('.markdown')?.textContent.length>10);
  results.partialStream = await page.locator('#cancel').isVisible();
  await screenshot('streaming');
  await waitIdle();
  check(await page.locator('.code-block').count()>0,'Missing code formatting');
  await screenshot('desktop-chat');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.locator('.code-block button').first().click();
  await page.waitForFunction(() => document.querySelector('.code-block button').textContent==='已复制');
  check((await page.evaluate(() => navigator.clipboard.readText())).includes('Hello, local workspace'),'Copy code failed');
  results.copy = true;
  results.populated = await page.evaluate(() => ({composerBottom:document.querySelector('#form').getBoundingClientRect().bottom,viewport:innerHeight,overflow:document.documentElement.scrollWidth>innerWidth}));
  check(!results.populated.overflow && results.populated.composerBottom<=901,'Populated composer outside viewport');
  await page.locator('.assistant-message .actions button').filter({hasText:'编辑后重发'}).last().click();
  check((await page.locator('#prompt').inputValue()).includes('本地聊天'),'Edit did not populate draft');
  await page.locator('#prompt').fill('停止验收，生成一段长回复。');
  await page.locator('#prompt').press('Enter');
  await page.locator('#cancel').waitFor({state:'visible'});
  await page.locator('#cancel').click();
  await waitIdle();
  check((await page.locator('#conversation').innerText()).includes('已停止'),'Stop was not reflected');
  results.stop = true;
  await page.locator('.assistant-message .actions button').filter({hasText:'重新生成'}).last().click();
  await page.locator('#cancel').waitFor({state:'visible'});
  await waitIdle();
  check((await page.locator('.markdown').last().innerText()).includes('Hello, local workspace'),'Regenerate failed');
  results.regenerate = true;
  await page.locator('#prompt').fill('长文本与草稿恢复测试。'.repeat(80));
  await page.waitForTimeout(900);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#prompt').value.length>100);
  results.draft = true;
  await page.locator('#prompt').fill('');
  await page.locator('#sidebarToggle').click();
  check(await page.locator('#sidebarToggle').getAttribute('aria-expanded')==='false','Desktop collapse failed');
  await screenshot('desktop-collapsed');
  await page.locator('#sidebarToggle').click();
  await page.locator('#appSettings').click();
  await page.locator('#preferencesDialog').waitFor({state:'visible'});
  await screenshot('settings');
  await page.locator('#themeDark').click();
  await page.locator('#closePreferences').click();
  check(await page.locator('html').getAttribute('data-theme')==='dark','Dark theme failed');
  await screenshot('dark');
  await page.locator('#appSettings').click();
  await page.locator('#themeSystem').click();
  await page.emulateMedia({colorScheme:'light'});
  await page.waitForFunction(() => document.documentElement.dataset.theme==='light');
  await page.emulateMedia({colorScheme:'dark'});
  await page.waitForFunction(() => document.documentElement.dataset.theme==='dark');
  results.systemTheme = true;
  await page.locator('#themeLight').click();
  await page.locator('#language').click();
  check(await page.locator('html').getAttribute('lang')==='en','English language failed');
  await page.locator('#language').click();
  await page.locator('#memoryNav').click();
  await page.locator('#memoryContent').fill('界面验收合成偏好：简洁排版。');
  await page.locator('#saveMemory').click();
  await page.locator('.memory-item').filter({hasText:'界面验收合成偏好'}).waitFor();
  results.memory = true;
  await screenshot('memory');
  await page.locator('#backMemory').click();
  await page.locator('#closePreferences').click();
  check(await page.locator('#appSettings').evaluate(el=>el===document.activeElement),'Dialog focus return failed');
  await page.locator('#mode').selectOption('image');
  await page.locator('#prompt').fill('合成图像布局验收');
  await page.locator('#prompt').press('Enter');
  await page.locator('#cancel').waitFor({state:'visible'});
  await screenshot('image-progress');
  await waitIdle();
  await page.locator('.result img').last().waitFor();
  check(await page.locator('.result img').last().evaluate(el=>el.complete&&el.naturalWidth>0),'Image failed to load');
  const downloaded = page.waitForEvent('download');
  await page.locator('.result a[download]').last().click();
  const download = await downloaded;
  check(await download.failure()===null,'Image download failed');
  results.imageDownload = true;
  await screenshot('image-result');
  await page.locator('#galleryNav').click();
  await page.locator('.gallery-card').first().click();
  await page.locator('#imageDialog').waitFor({state:'visible'});
  await screenshot('gallery-preview');
  await page.locator('#galleryEdit').click();
  await page.locator('#reference').waitFor({state:'visible'});
  await page.locator('#removeRef').click();
  results.galleryEdit = true;
  await page.locator('#renameChat').click();
  await page.locator('#chatName').fill('验收对话');
  await page.locator('#renameForm button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#chatTitle').textContent==='验收对话');
  await page.locator('#deleteCurrent').click();
  await page.locator('#undoDelete').waitFor({state:'visible'});
  await page.locator('#undoDelete').click();
  await page.waitForFunction(()=>document.querySelector('#chatTitle').textContent==='验收对话');
  results.renameTrashRestore = true;
  await page.setViewportSize({width:390,height:844});
  await page.locator('#mobileMenu').click();
  check(await page.locator('#mainContent').evaluate(el=>el.inert),'Mobile drawer must isolate main');
  await screenshot('mobile-sidebar');
  await page.keyboard.press('Escape');
  check(!await page.locator('#mainContent').evaluate(el=>el.inert),'Mobile escape failed');
  await screenshot('mobile-chat');
  await page.locator('.settings summary').click();
  await page.locator('#settingsPanel').waitFor({state:'visible'});
  await screenshot('mobile-generation-settings');
  await page.keyboard.press('Escape');
  results.widths = [];
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:844});
    const state=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,composerBottom:document.querySelector('#form').getBoundingClientRect().bottom}));
    check(state.scrollWidth<=width && state.composerBottom<=845,'Responsive overflow '+width);
    results.widths.push(state);
  }
  check(errors.length===0,'Browser errors: '+errors.join('; '));
  const receipt = {passed:true,...results,browserErrors:errors};
  console.log(JSON.stringify(receipt));
  return receipt;
}
